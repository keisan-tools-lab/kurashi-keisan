/**
 * サイト内のリンクを作る関数。
 * GitHub Pages では https://ユーザー名.github.io/kurashi-keisan/ のように
 * フォルダの下で公開されるので、リンクの前にそのフォルダ名を自動でつけます。
 *   link()       → トップページ
 *   link('pet')  → 犬・猫の年齢のページ
 */
export function link(path = ''): string {
  const base = import.meta.env.BASE_URL.replace(/\/$/, '');
  return `${base}/${path.replace(/^\//, '')}`;
}

